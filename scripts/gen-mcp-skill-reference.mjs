import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { MCP_TOOLS } from "../packages/mcp/src/constants.ts";

export const referenceRoot = new URL("../octonode-plugin/skills/octonode-connect/references/mcp/", import.meta.url);

function group(tool) {
  if (tool.path.includes("/github/")) return "github";
  if (tool.path.startsWith("/api/plugins")) return "plugins";
  if (/^project_(runs?|workflow_run|workflow_cancel)$/.test(tool.name)) return "runs";
  if (/^project_(workflow|native)/.test(tool.name)) return "workflows";
  return tool.projectScoped ? "source" : "workspace";
}

function example(schema, name = "") {
  if (name === "baseRevision") return "0".repeat(64);
  if (name === "path") return "src/example.ts";
  if (schema.enum) return schema.enum[0];
  if (schema.type === "object") {
    return Object.fromEntries((schema.required ?? []).map((key) => [key, example(schema.properties[key], key)]));
  }
  if (schema.type === "array") return [];
  if (["number", "integer"].includes(schema.type)) return schema.minimum ?? 1;
  if (name === "number") return "1";
  return name.endsWith("Id") || name === "id" ? "example-id" : "example";
}

const notes = {
  project_file_write: "Read the file first with `project_file_read`; use its exact revision as `baseRevision`. Reconcile conflicts by rereading.",
  project_node_source_write: "Read the node with `project_node_source_read` first; use the returned source revision.",
  project_node_signature_write: "Read the node source first. Its revision guards the signature change; validate the project afterward.",
  project_workflow_save: "Read `project_workflow_graph` first, preserve topology you do not intend to change, validate proposed edges, and use its exact graph revision.",
  project_plugin_node_add: "Inspect `project_plugin` and the target workflow graph before choosing a node and a stable instance ID. Read state before retrying an ambiguous add.",
  project_workflow_run: "Workflow runs may have side effects. Inspect returned events and the persisted run before reporting success.",
  project_workflow_cancel: "Identify the intended active run with `project_runs` or `project_run` before canceling it.",
  project_validate: "This compiles and synchronizes project source. Call after source changes and check the result.",
  project_pull_request_file: "Read `project_pull_request` and confirm its current head SHA before reviewing the file. The hosted tools do not publish reviews.",
};

function operationPage(tool, category) {
  const effect = tool.destructive ? `${tool.risk}; destructive` : tool.risk;
  const args = example(tool.inputSchema);
  if (tool.projectScoped) args.projectId = "example-project";
  const pathArgs = [...tool.path.matchAll(/\{([^}]+)\}/g)].map(([, key]) => key);
  const required = new Set(tool.inputSchema.required);
  const rows = Object.entries(tool.inputSchema.properties).map(([name, schema]) => {
    const details = [schema.type, schema.pattern && `pattern \`${schema.pattern}\``,
      schema.enum && `one of ${schema.enum.map((value) => `\`${value}\``).join(", ")}`,
      schema.description].filter(Boolean).join("; ");
    const destination = pathArgs.includes(name) ? "URL path" : (tool.query ?? []).includes(name)
      ? "query" : (tool.body ?? []).includes(name) ? "JSON body" : name === "projectId" && tool.projectScoped
        ? "project scope" : "tool argument";
    return `| \`${name}\` | ${required.has(name) ? "required" : "optional"} | ${destination} | ${details.replaceAll("|", "\\|")} |`;
  });
  return [
    `# ${tool.name}`, "",
    "Generated from the hosted MCP registration. Do not edit this file directly.", "",
    `[${category} router](../${category}.md) · [All categories](../index.md) · [Calling contract](../../mcp-calling.md)`, "",
    tool.description, "",
    "## When and how to call", "",
    `- Effect: **${effect}**.`,
    `- Scope: ${tool.projectScoped ? "workspace plus selected project. Pass `projectId` explicitly for a multi-project connection; otherwise the connection default applies." : "workspace. Pass any architecture or project identifier declared below."}`,
    `- Backend request: \`${tool.method} ${tool.path}\`. The MCP server fills the URL path, query, and body from the flat arguments below; do not send an HTTP request yourself.`,
    `- Result: ${tool.stream ? "bounded events in `data.events`" : tool.name === "profile_avatar_get" ? "`data.contentType` and `data.base64`" : "the upstream response in `data`"}. Check MCP \`isError\` and JSON \`ok\`.`,
    ...(notes[tool.name] ? [`- Before calling: ${notes[tool.name]}`] : []), "",
    "## Arguments", "",
    ...(rows.length ? ["| Name | Requirement | Routed to | Type and constraints |", "| --- | --- | --- | --- |", ...rows] : ["No arguments. Call with `{}`."]),
    "", "Bundled input schema (use the live tool schema if the deployed server differs):", "", "```json",
    JSON.stringify(tool.inputSchema, null, 2), "```", "",
    "## Example MCP tool call", "", "```json",
    JSON.stringify({ name: tool.name, arguments: args }, null, 2), "```", "",
    "Replace example IDs, paths, content, and revisions with live values. Never submit the zero revision.", "",
  ].join("\n");
}

export function renderReferences() {
  const files = new Map();
  const groups = Map.groupBy(MCP_TOOLS, group);
  const index = [
    "# Hosted MCP operation index", "",
    "Generated from `packages/mcp/src/constants.ts`; run `yarn gen:mcp-skills` after changing registrations.", "",
    "Read the [shared calling contract](../mcp-calling.md), then open one category router and one operation page.", "",
    `This bundle documents ${MCP_TOOLS.length} registered tools. Live \`tools/list\` is authoritative for the deployed server.`, "",
    "| Category | Use it for | Tools |", "| --- | --- | ---: |",
  ];
  const purposes = {
    workspace: "Profiles, conversations, notifications, and platform capabilities",
    github: "GitHub repositories, pull requests, review files, and jobs",
    source: "Project context, knowledge, files, nodes, and compilation",
    workflows: "Workflow graphs, topology, native nodes, and validation",
    plugins: "Installed project plugins and plugin nodes",
    runs: "Workflow execution, run inspection, and cancellation",
  };
  for (const [category, definitions] of groups) {
    const lines = [
      `# ${category === "github" ? "GitHub" : category[0].toUpperCase() + category.slice(1)} MCP operations`, "",
      "Choose one operation below, then read its page for the exact schema and calling example.", "",
      "[All categories](index.md) · [Shared calling contract](../mcp-calling.md)", "",
      "| Operation | When to use it | Effect |", "| --- | --- | --- |",
    ];
    for (const tool of definitions) {
      const effect = tool.destructive ? `${tool.risk}; destructive` : tool.risk;
      const summary = tool.description.split(". ")[0];
      lines.push(`| [\`${tool.name}\`](${category}/${tool.name}.md) | ${summary.replaceAll("|", "\\|")}${summary.endsWith(".") ? "" : "."} | ${effect} |`);
      files.set(`${category}/${tool.name}.md`, operationPage(tool, category));
    }
    index.push(`| [${category}](${category}.md) | ${purposes[category]} | ${definitions.length} |`);
    files.set(`${category}.md`, `${lines.join("\n")}\n`);
  }
  files.set("index.md", `${index.join("\n")}\n`);
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  rmSync(referenceRoot, { recursive: true, force: true });
  mkdirSync(referenceRoot, { recursive: true });
  for (const [name, content] of renderReferences()) {
    mkdirSync(new URL(".", new URL(name, referenceRoot)), { recursive: true });
    writeFileSync(new URL(name, referenceRoot), content);
  }
}
