import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { MCP_TOOLS } from "../packages/mcp/src/constants.ts";

export const referenceRoot = new URL("../connect-skill-plugin/skills/octonode-connect/references/mcp/", import.meta.url);

function group(tool) {
  if (tool.path.includes("/github/")) return "github";
  if (tool.path.startsWith("/api/plugins")) return "plugins";
  if (/^project_(runs?|workflow_run|workflow_cancel)$/.test(tool.name)) return "runs";
  if (/^project_(workflow|native)/.test(tool.name)) return "workflows";
  return tool.projectScoped ? "source" : "workspace";
}

function example(schema, name = "") {
  if (name === "baseRevision") return "0".repeat(64);
  if (name === "path") return "src/example.ts";
  if (schema.enum) return schema.enum[0];
  if (schema.type === "object") {
    return Object.fromEntries((schema.required ?? []).map((key) => [key, example(schema.properties[key], key)]));
  }
  if (schema.type === "array") return [];
  if (["number", "integer"].includes(schema.type)) return schema.minimum ?? 1;
  if (name === "number") return "1";
  return name.endsWith("Id") || name === "id" ? "example-id" : "example";
}

export function renderReferences() {
  const files = new Map();
  const groups = Map.groupBy(MCP_TOOLS, group);
  const index = [
    "# Hosted MCP operation index", "",
    "Generated from `packages/mcp/src/constants.ts`; run `yarn gen:mcp-skills` after changing registrations.", "",
    "Read the [shared calling contract](../mcp-calling.md) first. Load only the category needed.", "",
    "Examples show argument shapes, not executable project data. Replace every example ID, path, content,",
    "and revision with values from the user's request or live reads. Never submit the zero revision.", "",
    `All ${MCP_TOOLS.length} registered tools are listed below. Live tools/list is authoritative for the deployed server.`, "",
    "| Operation | Effect | Reference |", "| --- | --- | --- |",
  ];
  for (const [category, definitions] of groups) {
    const lines = [
      `# MCP operations: ${category}`, "",
      "Generated by `yarn gen:mcp-skills`. Do not edit this file manually.", "",
      "Read the [shared calling contract](../mcp-calling.md). [All operations](index.md).", "",
      "Examples use placeholder IDs/content and zero revisions. Replace them with live values before calling.", "",
      ...definitions.map(({ name }) => `- [${name}](#${name.replaceAll("_", "-")})`), "",
    ];
    for (const tool of definitions) {
      const effect = tool.destructive ? `${tool.risk}; destructive` : tool.risk;
      index.push(`| \`${tool.name}\` | ${effect} | [${category}](${category}.md#${tool.name.replaceAll("_", "-")}) |`);
      const args = example(tool.inputSchema);
      if (tool.projectScoped) args.projectId = "example-project";
      lines.push(
        `## ${tool.name.replaceAll("_", "-")}`, "", `Tool name: \`${tool.name}\``, "", tool.description, "",
        `- Effect: **${effect}** (registration metadata).`,
        `- Scope: ${tool.projectScoped ? "workspace and selected project; projectId overrides the connection default" : "workspace; any projectId argument is forwarded only as declared below"}.`,
        `- HTTP: \`${tool.method} ${tool.path}\`.`,
        `- Query arguments: ${(tool.query ?? []).map((key) => `\`${key}\``).join(", ") || "none"}.`,
        `- JSON body arguments: ${(tool.body ?? []).map((key) => `\`${key}\``).join(", ") || "none"}.`,
        `- Result: ${tool.stream ? "bounded event stream normalized to data.events" : tool.name === "profile_avatar_get" ? "data.contentType and data.base64" : "upstream JSON in data"}.`, "",
        "### Input schema", "", "```json", JSON.stringify(tool.inputSchema, null, 2), "```", "",
        "### Example arguments", "", "```json", JSON.stringify(args, null, 2), "```", "",
      );
    }
    files.set(`${category}.md`, lines.join("\n"));
  }
  files.set("index.md", `${index.join("\n")}\n`);
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(referenceRoot, { recursive: true });
  for (const [name, content] of renderReferences()) writeFileSync(new URL(name, referenceRoot), content);
}
